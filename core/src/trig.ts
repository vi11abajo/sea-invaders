/** sin(deg) scaled by 1000, for any integer degree. */
export function isin(deg: number): number {
  return SIN_1000[((deg % 360) + 360) % 360]!;
}

/** cos(deg) scaled by 1000, for any integer degree. */
export function icos(deg: number): number {
  return isin(deg + 90);
}
